def cosine(left: list[float], right: list[float]) -> float:
    if len(left) != len(right) or not left:
        return -1.0
    dot = 0.0
    left_norm = 0.0
    right_norm = 0.0
    for x_val, y_val in zip(left, right):
        dot += x_val * y_val
        left_norm += x_val * x_val
        right_norm += y_val * y_val
    if left_norm <= 0 or right_norm <= 0:
        return -1.0
    return dot / math.sqrt(left_norm * right_norm)


@dataclass(frozen=True)
class Meaning:
    name: str
    say: str
    again: str
    score: float


class MeaningIndex:
    def __init__(self) -> None:
        self._rows: list[tuple[str, str, str, list[float]]] = []

    def add(self, name: str, say: str, vector: list[float], again: str = "") -> None:
        self._rows.append((name, say, again or say, vector))

    def add_phrase(self, canonical: str, vector: list[float]) -> None:
        self.add(canonical, canonical, vector, canonical)

    def best(self, vector: list[float]) -> Meaning | None:
        winner: Meaning | None = None
        for name, say, again, row in self._rows:
            score = cosine(vector, row)
            if winner is None or score > winner.score:
                winner = Meaning(name, say, again, score)
        return winner
